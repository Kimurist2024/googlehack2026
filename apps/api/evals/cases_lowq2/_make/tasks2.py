"""質の低い提出物（cases_lowq2）の課題。合成データ専用。

各課題に、小さなモデルへ渡す英語の課題文（en）、課題どおりの模範解答（ref）、
動きの主張の型（claims）を置く。生徒は「模範解答どおりに動くはず」と思って説明を書く。
主張の正解は、生徒のコードを実際に動かして決める（build.py）。

主張の型:
- ("call", args, say)        関数を args で呼ぶ。say(v, *args) が文の候補を返す。v は生徒が思っている戻り値
- ("raises", args, say)      関数を args で呼んでエラーになるか。say(r, *args)、r は True/False
- ("stdin", stdin, say)      プログラムに stdin を渡して動かし、最後の行。say(v, stdin)
- ("line", stdin, line, say) 動かした出力に line の行があるか。say(present, line)
文の中の {N} {K} {H} {E} は、終わり方（なる・返す・表示・エラー）の言い回しにランダムに置きかえる。
"""

N = "{N}"  # 〜になる
K = "{K}"  # 〜を返す
H = "{H}"  # 〜と表示される


def L(x):
    return repr(x)


def tf(v, yes, no):
    return yes if v else no


def bool_say(name, what):
    """真偽を返す関数の文。what(arg) は「〜は素数」のような述語の文字列。"""
    def say(v, *a):
        arg = a[0]
        if v:
            return [f"{what(arg)}と判定される", f"{name}({L(arg)})はTrue{K}", f"{what(arg)}なのでTrue{N}"]
        return [f"{what(arg)}ではないと判定される", f"{name}({L(arg)})はFalse{K}", f"{what(arg)}じゃないからFalse{N}"]
    return say


